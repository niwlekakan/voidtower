//! Authoritative security metadata for HTTP routes and structured actions.
//!
//! S0-03 converges the session, bearer, risk, approval, and AI-exposure ledgers here. The
//! registry is immutable application code: adding a live route or dispatched action without a
//! complete typed record fails the inventory tests below.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum HttpMethod {
    Get,
    Post,
    Put,
    Patch,
    Delete,
}

impl HttpMethod {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Get => "GET",
            Self::Post => "POST",
            Self::Put => "PUT",
            Self::Patch => "PATCH",
            Self::Delete => "DELETE",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RoleTier {
    Session,
    Operator,
    Admin,
    Owner,
}

#[cfg(test)]
impl RoleTier {
    pub(crate) const fn wrong_role_probe(self) -> Option<&'static str> {
        match self {
            Self::Session => None,
            Self::Operator => Some("viewer"),
            Self::Admin => Some("operator"),
            Self::Owner => Some("admin"),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SessionPolicy {
    Public,
    Required(RoleTier),
    HandlerManaged,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CredentialPolicy {
    None,
    SessionCookie,
    BearerApiToken,
    WebhookHmac,
    PairingCode,
    NodeToken,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BearerPolicy {
    Public,
    Unscoped,
    Scope(&'static str),
    Denied,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RiskClass {
    Read,
    Mutate,
    Destructive,
    Irreversible,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ApprovalPolicy {
    NotApplicable,
    RiskLadder,
    Always,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AiExposure {
    None,
    Context,
    Callable,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RouteMetadata {
    pub method: HttpMethod,
    pub path: &'static str,
    pub session: SessionPolicy,
    pub credential: CredentialPolicy,
    pub bearer: BearerPolicy,
    pub risk: RiskClass,
    pub approval: ApprovalPolicy,
    pub ai_exposure: AiExposure,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ActionIngress {
    Mcp,
    Studio,
    Webhook,
    Automation,
    Internal,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ActionKind {
    Read,
    Mutating,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ActionMetadata {
    pub name: &'static str,
    pub ingresses: &'static [ActionIngress],
    pub kind: ActionKind,
    pub risk: RiskClass,
    pub approval: ApprovalPolicy,
    pub ai_exposure: AiExposure,
}

macro_rules! route_metadata {
    (
        $method:ident,
        $path:literal,
        $session:expr,
        $credential:expr,
        $bearer:expr,
        $risk:expr,
        $approval:expr,
        $ai_exposure:expr
    ) => {
        RouteMetadata {
            method: HttpMethod::$method,
            path: $path,
            session: $session,
            credential: $credential,
            bearer: $bearer,
            risk: $risk,
            approval: $approval,
            ai_exposure: $ai_exposure,
        }
    };
}

