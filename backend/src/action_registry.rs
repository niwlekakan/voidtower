pub fn route(method: &str, path: &str) -> Option<&'static RouteMetadata> {
    ROUTES
        .iter()
        .find(|metadata| metadata.method.as_str() == method && metadata.path == path)
}

pub fn action(name: &str) -> Option<&'static ActionMetadata> {
    ACTIONS.iter().find(|metadata| metadata.name == name)
}

