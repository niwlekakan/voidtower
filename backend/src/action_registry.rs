    #[test]
    fn every_dispatched_mcp_tool_has_action_metadata() {
        let source = include_str!("api/mcp.rs");
        let dispatch = source
            .split_once("let result = match name {")
            .expect("MCP tool dispatch match must remain discoverable")
            .1
            .split_once("other => Err(format!(\"Unknown tool: {other}\"))")
            .expect("MCP unknown-tool arm must remain discoverable")
            .0;
        let dispatched: Vec<&str> = dispatch
            .lines()
            .filter_map(|line| {
                let line = line.trim();
                let remainder = line.strip_prefix('"')?;
                let (name, _) = remainder.split_once("\" =>")?;
                Some(name)
            })
            .collect();
        assert!(
            !dispatched.is_empty(),
            "MCP dispatcher extraction returned no tools"
        );

        let missing: Vec<&str> = dispatched
            .iter()
            .copied()
            .filter(|name| action(name).is_none())
            .collect();
        assert!(
            missing.is_empty(),
            "dispatched MCP tools missing action metadata: {missing:?}"
        );

        let stale: Vec<&str> = ACTIONS
            .iter()
            .filter(|metadata| metadata.ingresses.contains(&ActionIngress::Mcp))
            .map(|metadata| metadata.name)
            .filter(|name| !dispatched.contains(name))
            .collect();
        assert!(
            stale.is_empty(),
            "MCP action metadata has no dispatcher arm: {stale:?}"
        );
    }

    #[test]
    fn every_structured_integration_action_has_action_metadata() {
        let source = include_str!("api/integrations.rs");
        let dispatch = source
            .split_once("let (resource_type, action_name, container_action, service_action) =")
            .expect("structured integration action match must remain discoverable")
            .1
            .split_once("other => return Err(AppError::BadRequest")
            .expect("structured integration unknown-action arm must remain discoverable")
            .0;

        let mut action_names = HashSet::new();
        for line in dispatch.lines().filter(|line| line.contains("=> (")) {
            let quoted: Vec<&str> = line.split('"').skip(1).step_by(2).collect();
            assert!(
                quoted.len() >= 3,
                "could not extract structured action name from {line:?}"
            );
            action_names.insert(quoted[2]);
        }
        assert!(!action_names.is_empty(), "no structured actions extracted");
        action_names.insert("automation.run");

        for action_name in &action_names {
            let metadata = action(action_name)
                .unwrap_or_else(|| panic!("integration action {action_name:?} lacks metadata"));
            assert_eq!(metadata.kind, ActionKind::Mutating);
            assert_eq!(metadata.ai_exposure, AiExposure::Callable);
            assert!(
                metadata.ingresses.contains(&ActionIngress::Webhook),
                "integration action {action_name:?} lacks webhook ingress metadata"
            );
        }

        let stale: Vec<&str> = ACTIONS
            .iter()
            .filter(|metadata| {
                metadata.ingresses.contains(&ActionIngress::Webhook)
                    || metadata.ingresses.contains(&ActionIngress::Automation)
            })
            .map(|metadata| metadata.name)
            .filter(|name| !action_names.contains(name))
            .collect();
        assert!(
            stale.is_empty(),
            "webhook/automation action metadata has no dispatcher: {stale:?}"
        );
    }

