#!/usr/bin/env python3
"""Check generated API contract artifacts against their source artifact.

`backend/contracts/api-v1-envelope-contract.json` is the source-owned contract.
`frontend/src/api/generatedApiContract.ts` and `docs/api-v1.openapi.json` are
generated from it by `scripts/generate-api-contract.mjs`.

That generator remains the byte-exact authority and runs in CI where Node is
provisioned. This module is the toolchain-independent drift check used by the
source-owned release gate: it re-derives the stamped source digest, the embedded
contract payload, and the published OpenAPI document from the source artifact and
reports bounded drift when any of them disagree. It never rewrites an artifact.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

SOURCE_REL = Path("backend/contracts/api-v1-envelope-contract.json")
GENERATED_TYPES_REL = Path("frontend/src/api/generatedApiContract.ts")
GENERATED_OPENAPI_REL = Path("docs/api-v1.openapi.json")
GENERATOR = "scripts/generate-api-contract.mjs"
HEADER = f"// Generated by {GENERATOR}; do not edit.\n"
STAMP = re.compile(
    r"^export const API_V1_ENVELOPE_CONTRACT_SOURCE_SHA256 = '([0-9a-f]{64})' as const\n$"
)
PAYLOAD_PREFIX = "export const API_V1_ENVELOPE_CONTRACT = "
PAYLOAD_SUFFIX = " as const\n"
MAX_ARTIFACT_BYTES = 8 * 1024 * 1024


def _read_bytes(path: Path, name: str) -> bytes:
    """Read one bounded artifact; failures are bounded and path-relative."""
    try:
        if path.stat().st_size > MAX_ARTIFACT_BYTES:
            raise ValueError(f"artifact exceeds the bounded size: {name}")
        return path.read_bytes()
    except OSError as exc:
        raise ValueError(f"artifact is unreadable: {name}") from exc


def parse_generated_types(text: str) -> tuple[str, object]:
    """Return the stamped source digest and embedded contract payload."""
    if not text.startswith(HEADER):
        raise ValueError("generated client artifact is missing its generator header")
    remainder = text[len(HEADER):]
    stamp, separator, body = remainder.partition("\n")
    match = STAMP.match(stamp + "\n")
    if not match:
        raise ValueError("generated client artifact has no valid source digest stamp")
    if not separator or not body.startswith(PAYLOAD_PREFIX) or not body.endswith(PAYLOAD_SUFFIX):
        raise ValueError("generated client artifact has no bounded contract payload")
    payload = body[len(PAYLOAD_PREFIX):-len(PAYLOAD_SUFFIX)]
    return match.group(1), json.loads(payload)


def check(root: Path) -> list[str]:
    """Return bounded drift findings; an empty list means the artifacts match."""
    problems: list[str] = []
    source_path = root / SOURCE_REL
    try:
        source_bytes = _read_bytes(source_path, SOURCE_REL.as_posix())
        source = json.loads(source_bytes.decode("utf-8"))
    except (ValueError, UnicodeDecodeError, json.JSONDecodeError):
        return [f"source contract is missing or unparseable: {SOURCE_REL.as_posix()}"]
    if not isinstance(source, dict) or not isinstance(source.get("openapi"), dict):
        return [f"source contract has no bounded OpenAPI document: {SOURCE_REL.as_posix()}"]
    expected_digest = hashlib.sha256(source_bytes).hexdigest()

    types_path = root / GENERATED_TYPES_REL
    try:
        digest, payload = parse_generated_types(_read_bytes(types_path, GENERATED_TYPES_REL.as_posix()).decode("utf-8"))
    except (ValueError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        problems.append(f"generated client artifact is unusable: {exc}")
    else:
        if digest != expected_digest:
            problems.append("generated client artifact stamps a stale source digest")
        if payload != source:
            problems.append("generated client artifact embeds a stale contract payload")

    openapi_path = root / GENERATED_OPENAPI_REL
    try:
        openapi = json.loads(_read_bytes(openapi_path, GENERATED_OPENAPI_REL.as_posix()).decode("utf-8"))
    except (ValueError, UnicodeDecodeError, json.JSONDecodeError):
        problems.append(f"published OpenAPI artifact is missing or unparseable: {GENERATED_OPENAPI_REL.as_posix()}")
    else:
        if openapi != source["openapi"]:
            problems.append("published OpenAPI artifact is stale against the source contract")

    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    args = parser.parse_args()
    problems = check(args.repo.resolve())
    if problems:
        for problem in problems:
            print(f"api contract drift: {problem}")
        return 1
    print("Generated API contract artifacts are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
