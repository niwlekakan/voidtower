#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(repositoryRoot, 'backend/contracts/api-v1-envelope-contract.json')
const outputPath = resolve(repositoryRoot, 'frontend/src/api/generatedApiContract.ts')
const sourceBytes = readFileSync(sourcePath)
const contract = JSON.parse(sourceBytes.toString('utf8'))
const sourceHash = createHash('sha256').update(sourceBytes).digest('hex')
const output = `// Generated by scripts/generate-api-contract.mjs; do not edit.\n` +
  `export const API_V1_ENVELOPE_CONTRACT_SOURCE_SHA256 = '${sourceHash}' as const\n` +
  `export const API_V1_ENVELOPE_CONTRACT = ${JSON.stringify(contract, null, 2)} as const\n`

if (process.argv.includes('--check')) {
  let existing
  try {
    existing = readFileSync(outputPath, 'utf8')
  } catch {
    process.stderr.write(`Generated contract is missing: ${outputPath}\n`)
    process.exit(1)
  }
  if (existing !== output) {
    process.stderr.write(`Generated contract is stale: ${outputPath}\n`)
    process.exit(1)
  }
  process.stdout.write(`Generated contract is current: ${outputPath}\n`)
} else {
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, output)
  process.stdout.write(`Generated ${outputPath} from ${sourcePath}\n`)
}
